#!/usr/bin/env python3
"""Regenerates lib/core/singbox/rules/iran_ip_ranges.g.dart.

Source: RIPE NCC's public delegated-extended statistics, which list every
IPv4/IPv6 block RIPE has delegated together with the holder's country. All
blocks marked IR (allocated or assigned) are merged into the smallest list
of CIDR prefixes.

    python3 scripts/update_iran_ip_ranges.py            # download latest
    python3 scripts/update_iran_ip_ranges.py FILE       # use a local copy
"""

import datetime
import ipaddress
import pathlib
import sys
import urllib.request

URL = "https://ftp.ripe.net/pub/stats/ripencc/delegated-ripencc-extended-latest"
OUT = (
    pathlib.Path(__file__).resolve().parent.parent
    / "lib/core/singbox/rules/iran_ip_ranges.g.dart"
)


def read_lines(argv):
    if len(argv) > 1:
        return pathlib.Path(argv[1]).read_text().splitlines()
    with urllib.request.urlopen(URL, timeout=120) as response:
        return response.read().decode().splitlines()


def main(argv):
    lines = read_lines(argv)
    serial = lines[0].split("|")[5] if lines and lines[0].startswith("2|") else "?"
    v4, v6 = [], []
    for line in lines:
        parts = line.split("|")
        if len(parts) < 7 or parts[1] != "IR":
            continue
        if parts[6] not in ("allocated", "assigned"):
            continue
        kind, start, value = parts[2], parts[3], int(parts[4])
        if kind == "ipv4":
            first = ipaddress.IPv4Address(start)
            last = first + value - 1
            v4.extend(ipaddress.summarize_address_range(first, last))
        elif kind == "ipv6":
            v6.append(ipaddress.IPv6Network(f"{start}/{value}"))
    v4 = list(ipaddress.collapse_addresses(v4))
    v6 = list(ipaddress.collapse_addresses(v6))
    if len(v4) < 500:
        sys.exit(f"suspiciously few IPv4 ranges ({len(v4)}), not writing")

    def dart_list(name, nets):
        body = "".join(f"  '{n}',\n" for n in nets)
        return f"const {name} = <String>[\n{body}];\n"

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// GENERATED by scripts/update_iran_ip_ranges.py - do not edit.\n"
        "//\n"
        "// IP blocks RIPE NCC has delegated to holders in Iran (country IR),\n"
        f"// from delegated-ripencc-extended (statistics date {serial},\n"
        f"// generated {datetime.date.today().isoformat()}).\n\n"
        + dart_list("iranIpv4Ranges", v4)
        + "\n"
        + dart_list("iranIpv6Ranges", v6)
    )
    print(f"{OUT}: {len(v4)} IPv4 + {len(v6)} IPv6 prefixes")


if __name__ == "__main__":
    main(sys.argv)
